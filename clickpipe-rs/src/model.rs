// serde дает Rust-структурам умение превращаться в JSON и обратно.
// Deserialize нужен для чтения входных JSON-событий.
// Serialize пригодится для отправки нормализованных событий дальше,
// например в ClickHouse в формате JSONEachRow.
use serde::{Deserialize, Serialize};

// RawEvent - это "сырой" формат события, как он приходит из внешнего мира.
//
// Почти все поля здесь Option<T>, потому что входные данные могут быть неполными:
// - поля может вообще не быть в JSON;
// - поле может быть null;
// - строка может быть пустой.
//
// Такая модель позволяет сначала прочитать событие без падения,
// а потом отдельно решить, валидное оно или нет.
#[derive(Debug, Deserialize)]
pub struct RawEvent {
    // Внешний идентификатор события.
    // Сейчас он обязателен на этапе валидации, но в сыром событии может отсутствовать.
    pub event_id: Option<String>,

    // Время события в исходном виде.
    // Пока это строка, без парсинга в DateTime.
    pub ts: Option<String>,

    // Источник события: например "api", "test", "backend".
    pub source: Option<String>,

    // Название события: например "login" или "deposit_success".
    pub event_name: Option<String>,

    // Идентификатор пользователя.
    // Он остается Option, потому что некоторые события могут быть анонимными.
    pub user_id: Option<u64>,

    // Произвольные дополнительные данные события.
    // serde_json::Value позволяет хранить объект, массив, строку, число, bool или null.
    pub payload: Option<serde_json::Value>,
}

// NormalizedEvent - это уже внутренний формат проекта.
//
// В нем обязательные поля перестают быть Option<T>, потому что validate.rs
// уже проверил, что они существуют и не пустые.
// Такой тип удобнее передавать дальше: в ClickHouse sink, буфер, retry-логику и т.д.
#[derive(Debug, Serialize)]
pub struct NormalizedEvent {
    // Проверенный непустой идентификатор события.
    pub event_id: String,

    // Проверенное непустое время события.
    // Позже его можно заменить на chrono::DateTime или другой строгий тип.
    pub ts: String,

    // Проверенный непустой источник события.
    pub source: String,

    // Проверенное непустое название события.
    pub event_name: String,

    // user_id по-прежнему опционален: отсутствие пользователя - допустимый кейс.
    pub user_id: Option<u64>,

    // payload всегда есть.
    // Если во входном событии payload отсутствовал, validate.rs подставит JSON null.
    pub payload: serde_json::Value,

    // Простой числовой отпечаток события.
    // Сейчас он считается локально и может пригодиться для поиска дублей или отладки.
    pub event_hash: u64,
}
